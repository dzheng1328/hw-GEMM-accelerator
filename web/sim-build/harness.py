"""Renders the C++ harness that drives rtl/accel.v (Verilator, --public-flat-rw) from JavaScript.

It replaces the cocotb testbench: it builds a fresh model per run, pokes the program, weights and input
image into the memories, applies reset, pulses start, clocks to done, and records one small record per
cycle. It reads internal signals only; no RTL file changes. The record layout is written out in the C++
comment above record() and decoded by web/src/live/trace/trace.ts."""

TEMPLATE = r"""// Generated by web/sim-build/harness.py for a @W@x@H@ mesh. Do not edit by hand.
#include "Vaccel.h"
#include "Vaccel___024root.h"
#include "verilated.h"

#include <emscripten.h>
#include <pthread.h>

#include <cstdint>
#include <cstring>
#include <vector>

// verilated_threads.cpp references these; the model is single-threaded, so they are never called.
extern "C" int pthread_setaffinity_np(pthread_t, size_t, const struct cpu_set_t*) { return 0; }
extern "C" int pthread_getaffinity_np(pthread_t, size_t, struct cpu_set_t*) { return 0; }
extern "C" int sched_getcpu(void) { return 0; }

namespace {

constexpr int NN = @NN@;
constexpr uint32_t RECORD_BYTES = 6 + 2 * NN;
constexpr uint32_t PROGRAM_WORDS = 4096;
constexpr uint32_t WEIGHT_WORDS = 65536;
constexpr uint32_t ACT_WORDS = 4 * 32768;
constexpr uint32_t PERF_WORDS = 4 + NN;  // run_cyc, slot_cyc, go_cyc, error_pc, then busy_cyc per node

VerilatedContext* ctx = nullptr;
Vaccel* top = nullptr;
std::vector<uint8_t> trace;
uint32_t perf[PERF_WORDS];

#define NODE(i, name) top->rootp->accel__DOT__mesh__DOT__g_node__BRA__##i##__KET____DOT__node__DOT__##name
#define XFER(i, valid, ready) ((NODE(i, valid) && NODE(i, ready)) ? 1u : 0u)
#define FLIT_TYPE(flit) ((static_cast<uint32_t>((flit)[4]) >> 10) & 3u)
#define NODE_WORD(i) static_cast<uint16_t>( \
    XFER(i, n_out_valid, n_out_ready) | (XFER(i, e_out_valid, e_out_ready) << 1) | \
    (XFER(i, s_out_valid, s_out_ready) << 2) | (XFER(i, w_out_valid, w_out_ready) << 3) | \
    (XFER(i, lcl_in_valid, lcl_in_ready) << 4) | ((NODE(i, res_valid) ? 1u : 0u) << 5) | \
    (FLIT_TYPE(NODE(i, n_out_flit)) << 6) | (FLIT_TYPE(NODE(i, e_out_flit)) << 8) | \
    (FLIT_TYPE(NODE(i, s_out_flit)) << 10) | (FLIT_TYPE(NODE(i, w_out_flit)) << 12) | \
    (FLIT_TYPE(NODE(i, lcl_in_flit)) << 14))

void eval_low() { top->clk = 0; top->eval(); }
void eval_high() { top->clk = 1; top->eval(); }

// One record per cycle, sampled just before the rising edge: valid && ready here is a transfer that edge captures.
// Record, little-endian, RECORD_BYTES = 6 + 2 * NN:
//   u16 busy mask (bit i: tile i busy)      u16 program read address      u8 flags (1 DMA, 2 write-back, 4 sequencer busy)
//   u8 0                                    then one u16 per node:
//     bits 0-3 a flit transferred on the N, E, S, W output link; bit 4 a flit injected at the local port;
//     bit 5 a RESULT delivered here; bits 6-15 the 2-bit flit type of N, E, S, W and the injected flit.
void record() {
    auto* r = top->rootp;
    uint16_t words[NN];
@NODE_WORDS@
    uint8_t rec[RECORD_BYTES];
    const uint16_t busy = r->accel__DOT__mesh_busy;
    const uint16_t pc = r->accel__DOT__prog_raddr;
    rec[0] = busy & 0xff;
    rec[1] = busy >> 8;
    rec[2] = pc & 0xff;
    rec[3] = pc >> 8;
    rec[4] = (r->accel__DOT__dma_busy ? 1 : 0) | (r->accel__DOT__wb_idle ? 0 : 2) | (r->accel__DOT__seq_busy ? 4 : 0);
    rec[5] = 0;
    for (int i = 0; i < NN; i++) {
        rec[6 + 2 * i] = words[i] & 0xff;
        rec[7 + 2 * i] = words[i] >> 8;
    }
    trace.insert(trace.end(), rec, rec + RECORD_BYTES);
}

void capture_perf() {
    auto* r = top->rootp;
    perf[0] = r->accel__DOT__g_perf__DOT__perf__DOT__run_cyc;
    perf[1] = r->accel__DOT__g_perf__DOT__perf__DOT__slot_cyc;
    perf[2] = r->accel__DOT__g_perf__DOT__perf__DOT__go_cyc;
    perf[3] = top->error_pc;
@PERF_BUSY@
}

uint64_t& act_word(uint32_t w) {
    auto* r = top->rootp;
    const uint32_t a = w >> 2;
    switch (w & 3) {
        case 0: return r->accel__DOT__g_act__BRA__0__KET____DOT__bank__DOT__mem[a];
        case 1: return r->accel__DOT__g_act__BRA__1__KET____DOT__bank__DOT__mem[a];
        case 2: return r->accel__DOT__g_act__BRA__2__KET____DOT__bank__DOT__mem[a];
        default: return r->accel__DOT__g_act__BRA__3__KET____DOT__bank__DOT__mem[a];
    }
}

}  // namespace

extern "C" {

EMSCRIPTEN_KEEPALIVE void sim_free() {
    delete top;
    delete ctx;
    top = nullptr;
    ctx = nullptr;
    trace.clear();
}

// A fresh model per run. The first eval runs the initial blocks (memories zero-filled), so the images
// must be loaded after it, never before.
EMSCRIPTEN_KEEPALIVE void sim_init() {
    sim_free();
    ctx = new VerilatedContext;
    // rtl/sim_mem.v calls $value$plusargs; Verilator aborts the first eval unless command args were set.
    static const char* kArgs[] = {"sim", nullptr};
    ctx->commandArgs(1, kArgs);
    top = new Vaccel(ctx);
    top->clk = 0;
    top->start = 0;
    top->rst = 1;
    top->eval();
    std::memset(perf, 0, sizeof perf);
}

EMSCRIPTEN_KEEPALIVE int sim_load(const uint64_t* program, uint32_t program_words, const uint64_t* weights,
                                  uint32_t weight_words) {
    if (!top || program_words > PROGRAM_WORDS || weight_words > WEIGHT_WORDS) return -1;
    auto* r = top->rootp;
    std::memcpy(r->accel__DOT__prog_mem__DOT__mem.data(), program, size_t(program_words) * 8);
    std::memcpy(r->accel__DOT__wt_mem__DOT__mem.data(), weights, size_t(weight_words) * 8);
    return 0;
}

EMSCRIPTEN_KEEPALIVE int sim_set_input(const uint64_t* words, uint32_t count) {
    if (!top || count > ACT_WORDS) return -1;
    for (uint32_t w = 0; w < count; w++) act_word(w) = words[w];
    return 0;
}

EMSCRIPTEN_KEEPALIVE int sim_run(uint32_t max_cycles) {
    if (!top) return -2;
    trace.clear();
    trace.reserve(size_t(RECORD_BYTES) * 150000);
    top->start = 0;
    top->rst = 1;
    for (int i = 0; i < 3; i++) { eval_low(); eval_high(); }
    top->rst = 0;
    eval_low(); eval_high();
    top->start = 1;
    eval_low(); eval_high();
    top->start = 0;
    uint32_t cycles = 0;
    while (!top->done && !top->error && cycles < max_cycles) {
        eval_low();
        record();
        eval_high();
        cycles++;
    }
    capture_perf();
    if (top->error) return -1;
    if (!top->done) return -2;
    return static_cast<int>(cycles);
}

EMSCRIPTEN_KEEPALIVE const uint8_t* sim_trace_ptr() { return trace.data(); }
EMSCRIPTEN_KEEPALIVE uint32_t sim_trace_bytes() { return static_cast<uint32_t>(trace.size()); }
EMSCRIPTEN_KEEPALIVE uint32_t sim_record_bytes() { return RECORD_BYTES; }

// Copies `count` 64-bit activation words starting at word `first_word` (striped over the four banks).
EMSCRIPTEN_KEEPALIVE int sim_copy_act(uint32_t first_word, uint32_t count, uint64_t* dst) {
    if (!top || first_word + count > ACT_WORDS) return -1;
    for (uint32_t i = 0; i < count; i++) dst[i] = act_word(first_word + i);
    return 0;
}

EMSCRIPTEN_KEEPALIVE uint32_t sim_perf(uint32_t index) { return index < PERF_WORDS ? perf[index] : 0; }

}  // extern "C"
"""


def render(w, h):
    nn = w * h
    node_words = "\n".join(f"    words[{i}] = NODE_WORD({i});" for i in range(nn))
    perf_busy = "\n".join(
        f"    perf[{4 + i}] = NODE({i}, g_perf__DOT__perf__DOT__busy_cyc);" for i in range(nn)
    )
    return (
        TEMPLATE.replace("@W@", str(w)).replace("@H@", str(h)).replace("@NN@", str(nn))
        .replace("@NODE_WORDS@", node_words).replace("@PERF_BUSY@", perf_busy)
    )
